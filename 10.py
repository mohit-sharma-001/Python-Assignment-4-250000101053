# Question 10: Write a program to demonstrate the use of ceil(), floor() and sqrt() functions.

import math

val = 7.35

print(f"Value: {val}")
print("math.ceil()  (smallest integer >= x) :", math.ceil(val))
print("math.floor() (largest integer <= x)  :", math.floor(val))
print("math.sqrt(49)                       :", math.sqrt(49))
