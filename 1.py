# Question 1: Write a program to demonstrate the use of abs(), round() and pow() functions.

# abs()
val = -25.75
print(f"abs({val}) =", abs(val))

# round()
pi = 3.14159265
print(f"round({pi}, 3) =", round(pi, 3))
print(f"round(4.6) =", round(4.6))

# pow()
print("pow(2, 5) =", pow(2, 5))
print("pow(3, 4, 10) =", pow(3, 4, 10))  # (3^4) % 10
